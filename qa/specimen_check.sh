#!/usr/bin/env bash
# Regenerates qa/specimen-check.txt for the shipped specimen PDF. Run from the workspace root:
#   bash builds/A4-letterform/qa/specimen_check.sh
# Mechanical receipts (pdfinfo, qpdf, pdffonts, overflow_check.mjs, pdftotext) are regenerated; the page-inspection note at the end is written by hand after looking at the rendered pages.
set -euo pipefail
B="$(cd "$(dirname "$0")/.." && pwd)"; P="$B/specimen/Apertide-Specimen.pdf"; OUT="$B/qa/specimen-check.txt"
VER=$(python3 -c "from fontTools.ttLib import TTFont;import glob;f=TTFont(sorted(glob.glob('$B/fonts/*.ttf'))[0]);print(f['name'].getDebugName(5))")
{
echo "# Specimen PDF checks — build ${VER#Version } (regenerated by qa/specimen_check.sh)"; echo
pdfinfo "$P" | grep -E "^(Producer|Pages|Page size|File size)"
echo "SHA-256:         $(sha256sum "$P" | cut -c1-64)"; echo
echo "## qpdf --check"; qpdf --check "$P" 2>&1 | grep -v "^checking" || true; echo
echo "## pdffonts summary (variable-font settings are emitted by Skia as Type 3 glyph procedures; see colophon rendering note)"
pdffonts "$P" | tail -n +3 > /tmp/pdffonts.txt
echo "fonts listed: $(wc -l < /tmp/pdffonts.txt)"
echo "CID TrueType (static instances): $(grep -c "CID TrueType" /tmp/pdffonts.txt || true)"
echo "Type 3 (variable-font settings): $(grep -c "Type 3" /tmp/pdffonts.txt || true)"
echo "all embedded:       $(grep -cE '\s(yes)\s+(yes|no)\s+(yes|no)\s+[0-9]+\s+[0-9]+\s*$' /tmp/pdffonts.txt) yes (emb column)"
echo "non-Apertide fonts: $(grep -vc Apertide /tmp/pdffonts.txt || true)"; echo
echo "## layout receipt — specimen/overflow_check.mjs (Chromium print layout: side margins, folio zone, clipped nowrap text)"
(cd "$B/.." && node "$B/specimen/overflow_check.mjs" 2>&1 | tail -n 2); echo
echo "## text extraction sample (page 8)"; pdftotext -f 8 -l 8 -layout "$P" - | sed 's/^ *//' | grep -v "^$" | head -8
echo "## text extraction (cover and colophon counts)"
echo "cover figures (pdftotext page 1, the GLYPHS / ENCODED / PAGES counters): $(pdftotext -f 1 -l 1 "$P" - | grep -E '^[0-9]+$' | head -3 | tr '\n' ' ')"
pdftotext -f 15 -l 15 "$P" - | grep -E "^Version" | head -1; echo
echo "## page inspection"
cat "$B/qa/specimen-inspection-note.txt"
} > "$OUT"
echo "wrote $OUT"
